create table if not exists public.tbl_data_subject_requests (
  id bigint generated by default as identity primary key,
  user_id integer not null references public.tbl_users(id) on delete restrict,
  request_type text not null check (request_type in ('access','correction','erasure','grievance')),
  details text not null default '' check (length(details) <= 4000),
  status text not null default 'submitted' check (status in ('submitted','in_review','completed','rejected')),
  due_at timestamptz not null default (now() + interval '30 days'),
  resolved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists tbl_data_subject_requests_open_uidx
on public.tbl_data_subject_requests(user_id,request_type)
where status in ('submitted','in_review');

create index if not exists tbl_data_subject_requests_user_created_idx
on public.tbl_data_subject_requests(user_id,created_at desc,id desc);

alter table public.tbl_data_subject_requests enable row level security;
revoke all on public.tbl_data_subject_requests from public,anon,authenticated;

create or replace function private.submit_data_subject_request(p_request_type text,p_details text default '')
returns public.tbl_data_subject_requests
language plpgsql
security definer
set search_path=''
as $$
declare
  me integer:=public.get_current_app_user_id();
  clean_type text:=lower(trim(coalesce(p_request_type,'')));
  clean_details text:=trim(coalesce(p_details,''));
  result public.tbl_data_subject_requests;
begin
  if clean_type not in ('access','correction','erasure','grievance') then
    raise exception 'Unsupported data request type' using errcode='22023';
  end if;
  if length(clean_details)>4000 then
    raise exception 'Request details must be 4000 characters or fewer' using errcode='22023';
  end if;
  perform pg_advisory_xact_lock(hashtextextended(me::text||':'||clean_type,0));
  select * into result from public.tbl_data_subject_requests
  where user_id=me and request_type=clean_type and status in ('submitted','in_review')
  order by id desc limit 1;
  if result.id is null then
    insert into public.tbl_data_subject_requests(user_id,request_type,details)
    values(me,clean_type,clean_details)
    returning * into result;
  end if;
  return result;
end
$$;

create or replace function public.submit_data_subject_request(p_request_type text,p_details text default '')
returns public.tbl_data_subject_requests
language sql
security definer
set search_path=''
as $$ select private.submit_data_subject_request(p_request_type,p_details) $$;

create or replace function private.list_my_data_subject_requests(p_limit integer default 26,p_before timestamptz default null)
returns setof public.tbl_data_subject_requests
language sql
stable
security definer
set search_path=''
as $$
  select r.* from public.tbl_data_subject_requests r
  where r.user_id=public.get_current_app_user_id()
    and (p_before is null or r.created_at<p_before)
  order by r.created_at desc,r.id desc
  limit greatest(1,least(coalesce(p_limit,26),101))
$$;

create or replace function public.list_my_data_subject_requests(p_limit integer default 26,p_before timestamptz default null)
returns setof public.tbl_data_subject_requests
language sql
stable
security definer
set search_path=''
as $$ select * from private.list_my_data_subject_requests(p_limit,p_before) $$;

revoke all on function private.submit_data_subject_request(text,text) from public,anon,authenticated;
revoke all on function private.list_my_data_subject_requests(integer,timestamptz) from public,anon,authenticated;
revoke all on function public.submit_data_subject_request(text,text) from public,anon;
revoke all on function public.list_my_data_subject_requests(integer,timestamptz) from public,anon;
grant execute on function public.submit_data_subject_request(text,text) to authenticated;
grant execute on function public.list_my_data_subject_requests(integer,timestamptz) to authenticated;
