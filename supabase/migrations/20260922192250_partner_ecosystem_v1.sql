create or replace function private.normalize_partner_status()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  new.status := case upper(coalesce(new.status, 'DRAFT'))
    when 'ACTIVE' then 'APPROVED'
    when 'PENDING' then 'UNDER_REVIEW'
    when 'DRAFT' then 'DRAFT'
    when 'UNDER_REVIEW' then 'UNDER_REVIEW'
    when 'APPROVED' then 'APPROVED'
    when 'REJECTED' then 'REJECTED'
    when 'SUSPENDED' then 'SUSPENDED'
    else new.status
  end;
  new.updated_at := now();
  return new;
end $$;

drop trigger if exists normalize_partner_status on public.tbl_partner_profiles;
create trigger normalize_partner_status
before insert or update of status on public.tbl_partner_profiles
for each row execute function private.normalize_partner_status();

