create or replace function private.refresh_partner_settlement(p_event_id integer)
returns void language plpgsql security definer set search_path='' as $$
declare
  e public.tbl_events;
  config public.tbl_partner_finance_config;
  gross bigint; fee bigint; gst bigint; refunded bigint; net bigint;
begin
  select * into e from public.tbl_events where id=p_event_id;
  if e.id is null then return; end if;
  select * into config from public.tbl_partner_finance_config where singleton;
  select coalesce(sum(amount_paisa),0),coalesce(sum(platform_fee_paisa),0),
    coalesce(sum(gst_paisa),0)
  into gross,fee,gst from public.tbl_activity_payments
  where event_id=p_event_id and status='paid';
  select coalesce(sum(amount_paisa),0) into refunded
  from public.tbl_partner_financial_events
  where event_id=p_event_id and kind in ('REFUND','CHARGEBACK','REVERSAL') and status='SUCCEEDED';
  net:=greatest(0,gross-fee-gst-refunded);
  insert into public.tbl_partner_settlements(
    event_id,partner_user_id,status,gross_paisa,platform_fee_paisa,gst_paisa,
    refund_paisa,expected_net_paisa,eligible_at,due_at
  ) values (
    p_event_id,e.created_by,'PENDING',gross,fee,gst,refunded,net,
    e.event_end_time,e.event_end_time+make_interval(days=>config.settlement_days)
  ) on conflict(event_id) do update set
    gross_paisa=excluded.gross_paisa,platform_fee_paisa=excluded.platform_fee_paisa,
    gst_paisa=excluded.gst_paisa,refund_paisa=excluded.refund_paisa,
    expected_net_paisa=excluded.expected_net_paisa,
    eligible_at=excluded.eligible_at,due_at=excluded.due_at,
    status=case when public.tbl_partner_settlements.status='PAID'
      and public.tbl_partner_settlements.expected_net_paisa<>excluded.expected_net_paisa then 'ON_HOLD'
      else public.tbl_partner_settlements.status end,
    updated_at=now();
end $$;

create or replace function private.queue_required_refund(
  p_payment public.tbl_activity_payments, p_reason text
) returns void language plpgsql security definer set search_path='' as $$
declare host_id integer;
begin
  select created_by into host_id from public.tbl_events where id=p_payment.event_id;
  insert into public.tbl_partner_financial_events(
    payment_id,event_id,partner_user_id,participant_user_id,kind,status,
    amount_paisa,idempotency_key,reason
  ) values (
    p_payment.id,p_payment.event_id,host_id,p_payment.user_id,'REFUND','REQUIRED',
    p_payment.amount_paisa,'refund-required:'||p_payment.id::text,p_reason
  ) on conflict(idempotency_key) do nothing;
  update public.tbl_activity_payments set financial_status='REFUND_REQUIRED'
  where id=p_payment.id and financial_status<>'REFUNDED';
  perform private.enqueue_notification(
    p_payment.user_id,'payment_refund_required','Refund review started',
    'Your payment was verified but the activity could not confirm your place. WeNitro has opened a refund case.',
    p_payment.event_id::text,null,jsonb_build_object('payment_id',p_payment.id,'reason',p_reason)
  );
  perform private.refresh_partner_settlement(p_payment.event_id);
end $$;

