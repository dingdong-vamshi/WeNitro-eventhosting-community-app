create or replace function public.prepare_activity_payment(p_event_id integer)
returns public.tbl_activity_payments language plpgsql security definer set search_path='' as $$
declare
  me integer:=public.get_current_app_user_id();
  event_row public.tbl_events;
  participation public.tbl_event_participants;
  payment public.tbl_activity_payments;
  amount_minor bigint; occupied integer; generated_order_id text;
begin
  if auth.uid() is null or me is null then raise exception 'Authentication required' using errcode='42501'; end if;
  select * into event_row from public.tbl_events
  where id=p_event_id and status='published' and not coalesce(is_deleted,false)
    and not coalesce(is_cancelled,false) for update;
  if event_row.id is null then raise exception 'Activity is unavailable'; end if;
  if not private.has_active_partner(event_row.created_by) then
    raise exception 'Paid checkout is unavailable while the Partner account is not approved' using errcode='42501';
  end if;
  if event_row.payment_collection_mode<>'cashfree' then raise exception 'Online checkout is unavailable'; end if;
  perform private.assert_registration_complete(p_event_id,me);
  if event_row.created_by=me then raise exception 'Hosts cannot pay to join their own activity'; end if;
  if event_row.registration_close_time is not null and event_row.registration_close_time<now() then raise exception 'Registration is closed'; end if;
  if not event_row.is_paid or event_row.price<=0 then raise exception 'This activity does not require payment'; end if;
  if coalesce(event_row.currency,'INR')<>'INR' then raise exception 'Only INR activities are supported'; end if;
  amount_minor:=round(event_row.price*100)::bigint;
  if amount_minor<=0 or abs(event_row.price*100-amount_minor)>0.000001 then raise exception 'Activity price must have at most two decimal places'; end if;
  select * into participation from public.tbl_event_participants
  where event_id=p_event_id and user_id=me for update;
  if participation.status in ('approved','going') then raise exception 'You have already joined this activity'; end if;
  if event_row.join_type='approval' and coalesce(participation.status,'')<>'payment_required' then raise exception 'Host approval is required before payment'; end if;
  update public.tbl_activity_payments set status='expired',provider_status=coalesce(provider_status,'LOCAL_EXPIRED'),updated_at=now()
  where event_id=p_event_id and user_id=me and status in ('created','pending') and checkout_expires_at<=now();
  select * into payment from public.tbl_activity_payments
  where event_id=p_event_id and user_id=me and status in ('created','pending') and checkout_expires_at>now()
  order by created_at desc limit 1 for update;
  if payment.id is not null then
    if payment.amount_paisa<>amount_minor or payment.currency<>'INR' then raise exception 'The activity price changed; start a new payment attempt'; end if;
    return payment;
  end if;
  select count(*) into occupied from public.tbl_event_participants
  where event_id=p_event_id and user_id<>me and status in ('approved','going','payment_required');
  if event_row.max_participants is not null and occupied>=event_row.max_participants then raise exception 'Activity is full'; end if;
  if event_row.join_type<>'approval' then
    insert into public.tbl_event_participants(event_id,user_id,status,responded_at,joined_at)
    values(p_event_id,me,'payment_required',null,null)
    on conflict(event_id,user_id) do update set status=case when public.tbl_event_participants.status in ('approved','going')
      then public.tbl_event_participants.status else 'payment_required' end,responded_at=null,joined_at=null;
  end if;
  generated_order_id:='wn_'||p_event_id::text||'_'||me::text||'_'||substr(replace(gen_random_uuid()::text,'-',''),1,20);
  insert into public.tbl_activity_payments(event_id,user_id,partner_user_id,provider_order_id,amount_paisa,currency,status,checkout_expires_at)
  values(p_event_id,me,event_row.created_by,generated_order_id,amount_minor,'INR','created',now()+interval '20 minutes')
  returning * into payment;
  return payment;
end $$;

create or replace function public.finalize_activity_payment(
  p_order_id text,p_provider_payment_id text,p_amount_paisa bigint,p_currency text,
  p_provider_status text,p_provider_metadata jsonb default '{}'::jsonb
) returns public.tbl_activity_payments language plpgsql security definer set search_path='' as $$
declare payment public.tbl_activity_payments; event_row public.tbl_events; occupied integer; exception_reason text;
begin
  select * into payment from public.tbl_activity_payments where provider_order_id=p_order_id for update;
  if payment.id is null then raise exception 'Payment order not found'; end if;
  if payment.status='paid' then
    if payment.amount_paisa<>p_amount_paisa or payment.currency<>p_currency
      or coalesce(payment.provider_payment_id,'')<>coalesce(nullif(p_provider_payment_id,''),payment.provider_payment_id,'') then
      raise exception 'Conflicting paid-payment replay';
    end if;
    return payment;
  end if;
  if p_provider_status not in ('PAID','SUCCESS') then raise exception 'Provider has not confirmed payment'; end if;
  if payment.amount_paisa<>p_amount_paisa or payment.currency<>p_currency then raise exception 'Provider payment amount does not match the server ledger'; end if;
  select * into event_row from public.tbl_events where id=payment.event_id for update;
  if event_row.id is null or coalesce(event_row.is_deleted,false) or coalesce(event_row.is_cancelled,false) then
    exception_reason:='ACTIVITY_UNAVAILABLE_AFTER_PAYMENT';
  else
    select count(*) into occupied from public.tbl_event_participants
    where event_id=payment.event_id and user_id<>payment.user_id and status in ('approved','going');
    if event_row.max_participants is not null and occupied>=event_row.max_participants then
      exception_reason:='CAPACITY_UNAVAILABLE_AFTER_PAYMENT';
    end if;
  end if;
  update public.tbl_activity_payments set
    status='paid',provider_status=p_provider_status,
    provider_payment_id=coalesce(nullif(p_provider_payment_id,''),provider_payment_id),
    provider_metadata=coalesce(provider_metadata,'{}'::jsonb)||coalesce(p_provider_metadata,'{}'::jsonb),
    paid_at=coalesce(paid_at,now()),last_verified_at=now(),updated_at=now(),
    financial_status=case when exception_reason is null then 'PAYABLE' else 'REFUND_REQUIRED' end
  where id=payment.id returning * into payment;
  if exception_reason is null then
    insert into public.tbl_event_participants(event_id,user_id,status,responded_at,joined_at)
    values(payment.event_id,payment.user_id,'approved',now(),now())
    on conflict(event_id,user_id) do update set status='approved',responded_at=now(),joined_at=coalesce(public.tbl_event_participants.joined_at,now());
    insert into public.tbl_partner_financial_events(payment_id,event_id,partner_user_id,participant_user_id,kind,status,amount_paisa,idempotency_key,provider_reference)
    values(payment.id,payment.event_id,event_row.created_by,payment.user_id,'PAYMENT','SUCCEEDED',payment.amount_paisa,'payment:'||payment.id::text,payment.provider_payment_id)
    on conflict(idempotency_key) do nothing;
    perform private.enqueue_notification(payment.user_id,'payment_confirmed','Payment confirmed',
      'Your payment is verified and your place is confirmed.',payment.event_id::text,null,jsonb_build_object('payment_id',payment.id));
    perform private.refresh_partner_settlement(payment.event_id);
  else
    update public.tbl_event_participants set status='left',responded_at=now(),joined_at=null
    where event_id=payment.event_id and user_id=payment.user_id;
    perform private.queue_required_refund(payment,exception_reason);
  end if;
  return payment;
end $$;

create or replace function public.cancel_activity(p_event_id integer)
returns void language plpgsql security definer set search_path='' as $$
declare me integer:=public.get_current_app_user_id(); payment public.tbl_activity_payments;
begin
  if not private.can_manage_activity(p_event_id,me) then raise exception 'Activity not found or not manageable' using errcode='42501'; end if;
  update public.tbl_events set is_cancelled=true,status='cancelled',updated_by=me,updated_at=now() where id=p_event_id;
  for payment in select * from public.tbl_activity_payments where event_id=p_event_id and status='paid' and financial_status not in ('REFUNDED','REVERSED') loop
    perform private.queue_required_refund(payment,'ACTIVITY_CANCELLED_BY_HOST');
  end loop;
  update public.tbl_partner_settlements set status='ON_HOLD',note='Activity cancelled; refund review required',updated_at=now()
  where event_id=p_event_id and status<>'PAID';
end $$;

