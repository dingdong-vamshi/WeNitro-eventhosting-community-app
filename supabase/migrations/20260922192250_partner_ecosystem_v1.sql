create or replace function private.snapshot_activity_payment_fee()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  config public.tbl_partner_finance_config;
  tax_base bigint;
begin
  if tg_op='UPDATE' and old.status='paid' then
    if new.amount_paisa is distinct from old.amount_paisa
       or new.currency is distinct from old.currency
       or new.provider_order_id is distinct from old.provider_order_id
       or new.provider_payment_id is distinct from old.provider_payment_id
       or new.platform_fee_bps is distinct from old.platform_fee_bps
       or new.platform_fee_paisa is distinct from old.platform_fee_paisa
       or new.gst_bps is distinct from old.gst_bps
       or new.gst_paisa is distinct from old.gst_paisa
       or new.gst_basis is distinct from old.gst_basis
       or new.partner_net_paisa is distinct from old.partner_net_paisa
       or new.paid_at is distinct from old.paid_at then
      raise exception 'Verified payment evidence and accounting are immutable';
    end if;
  end if;
  if new.status='paid' and (tg_op='INSERT' or old.status is distinct from 'paid') then
    select * into config from public.tbl_partner_finance_config where singleton;
    new.platform_fee_bps := config.platform_fee_bps;
    new.platform_fee_paisa := round(new.amount_paisa::numeric*config.platform_fee_bps/10000)::bigint;
    new.gst_bps := case when config.gst_enabled then config.gst_bps else 0 end;
    new.gst_basis := config.gst_basis;
    tax_base := case config.gst_basis when 'gross' then new.amount_paisa
      when 'platform_fee' then new.platform_fee_paisa else 0 end;
    new.gst_paisa := case when config.gst_enabled
      then round(tax_base::numeric*config.gst_bps/10000)::bigint else 0 end;
    if new.platform_fee_paisa+new.gst_paisa>new.amount_paisa then
      raise exception 'Configured deductions exceed gross payment';
    end if;
    new.partner_net_paisa := new.amount_paisa-new.platform_fee_paisa-new.gst_paisa;
    new.financial_status := 'PAYABLE';
  elsif new.status<>'paid' and tg_op='INSERT' then
    new.platform_fee_bps:=null; new.platform_fee_paisa:=null;
    new.gst_bps:=null; new.gst_paisa:=null; new.gst_basis:=null;
    new.partner_net_paisa:=null;
  end if;
  return new;
end $$;

