create or replace function private.mask_financial_value(p_value text, p_visible integer default 4)
returns text language sql immutable set search_path = '' as $$
  select case
    when nullif(btrim(coalesce(p_value, '')), '') is null then ''
    when char_length(p_value) <= p_visible then repeat('•', char_length(p_value))
    else repeat('•', greatest(4, char_length(p_value) - p_visible)) || right(p_value, p_visible)
  end
$$;

create or replace function private.get_my_partner_profile()
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare
  me integer := public.get_current_app_user_id();
  profile jsonb;
  payout jsonb;
begin
  if auth.uid() is null or me is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;
  select to_jsonb(p) into profile
  from public.tbl_partner_profiles p where p.user_id = me;
  select jsonb_build_object(
    'bank_name', a.bank_name,
    'account_holder_name', a.account_holder_name,
    'account_number_masked', private.mask_financial_value(a.account_number, 4),
    'ifsc_masked', private.mask_financial_value(a.ifsc, 4),
    'upi_id_masked', case when a.upi_id = '' then ''
      when position('@' in a.upi_id) > 0 then left(a.upi_id,1) || '•••@' || split_part(a.upi_id,'@',2)
      else private.mask_financial_value(a.upi_id,3) end,
    'review_status', a.review_status,
    'review_reason', a.review_reason,
    'updated_at', a.updated_at
  ) into payout
  from public.tbl_partner_payout_accounts a where a.user_id = me;
  return jsonb_build_object(
    'profile', profile,
    'payout_account', payout,
    'eligible', private.partner_eligible(me),
    'can_host_paid', private.has_active_partner(me)
  );
end $$;

create or replace function private.submit_partner_application(p_application jsonb)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  me integer := public.get_current_app_user_id();
  previous_status text;
  next_status text;
  activity_types text[];
  profile public.tbl_partner_profiles;
begin
  if auth.uid() is null or not private.partner_eligible(me) then
    raise exception 'Verify your email or phone before applying as a Partner' using errcode = '42501';
  end if;
  if jsonb_typeof(p_application) is distinct from 'object' then
    raise exception 'Partner application must be an object' using errcode = '22023';
  end if;
  if char_length(btrim(coalesce(p_application->>'business_name',''))) not between 2 and 120
     or char_length(btrim(coalesce(p_application->>'city',''))) not between 2 and 120
     or char_length(btrim(coalesce(p_application->>'activity_location',''))) not between 2 and 240
     or char_length(btrim(coalesce(p_application->>'age_category',''))) not between 2 and 80 then
    raise exception 'Business name, city, activity location and age category are required' using errcode = '22023';
  end if;
  if jsonb_typeof(coalesce(p_application->'activity_types','[]'::jsonb)) <> 'array'
     or jsonb_array_length(coalesce(p_application->'activity_types','[]'::jsonb)) not between 1 and 20 then
    raise exception 'Choose at least one activity type' using errcode = '22023';
  end if;
  select array_agg(distinct btrim(value) order by btrim(value)) into activity_types
  from jsonb_array_elements_text(p_application->'activity_types') x(value)
  where btrim(value) <> '';
  if coalesce(cardinality(activity_types), 0) = 0 then
    raise exception 'Choose at least one activity type' using errcode = '22023';
  end if;

  perform 1 from public.tbl_users where id = me for update;
  select status into previous_status from public.tbl_partner_profiles where user_id = me for update;
  if previous_status = 'SUSPENDED' then
    raise exception 'A suspended Partner account must be reviewed by WeNitro' using errcode = '42501';
  end if;
  next_status := case when previous_status='APPROVED' then 'APPROVED' else 'UNDER_REVIEW' end;

  insert into public.tbl_partner_profiles(
    user_id, business_name, description, city, activity_types,
    activity_location, age_category, status, submitted_at,
    reviewed_at, reviewed_by, decision_reason
  ) values (
    me, btrim(p_application->>'business_name'),
    left(btrim(coalesce(p_application->>'description','')), 1000),
    btrim(p_application->>'city'), activity_types,
    btrim(p_application->>'activity_location'), btrim(p_application->>'age_category'),
    next_status, now(), null, null, null
  )
  on conflict(user_id) do update set
    business_name = excluded.business_name,
    description = excluded.description,
    city = excluded.city,
    activity_types = excluded.activity_types,
    activity_location = excluded.activity_location,
    age_category = excluded.age_category,
    status = next_status, submitted_at = now(),
    reviewed_at = case when next_status='APPROVED' then public.tbl_partner_profiles.reviewed_at else null end,
    reviewed_by = case when next_status='APPROVED' then public.tbl_partner_profiles.reviewed_by else null end,
    decision_reason = case when next_status='APPROVED' then public.tbl_partner_profiles.decision_reason else null end,
    updated_at = now()
  returning * into profile;

  if nullif(btrim(coalesce(p_application->>'account_number','')), '') is null
     and nullif(btrim(coalesce(p_application->>'upi_id','')), '') is null then
    raise exception 'Provide a bank account number or UPI ID' using errcode = '22023';
  end if;

  insert into public.tbl_partner_payout_accounts(
    user_id, bank_name, account_holder_name, account_number, ifsc, upi_id,
    review_status, reviewed_at, reviewed_by, review_reason, updated_at
  ) values (
    me,
    left(btrim(coalesce(p_application->>'bank_name','')),120),
    left(btrim(coalesce(p_application->>'account_holder_name','')),160),
    left(regexp_replace(coalesce(p_application->>'account_number',''),'[^A-Za-z0-9]','','g'),34),
    upper(left(regexp_replace(coalesce(p_application->>'ifsc',''),'\s','','g'),20)),
    lower(left(btrim(coalesce(p_application->>'upi_id','')),160)),
    'UNDER_REVIEW', null, null, null, now()
  )
  on conflict(user_id) do update set
    bank_name = excluded.bank_name,
    account_holder_name = excluded.account_holder_name,
    account_number = excluded.account_number,
    ifsc = excluded.ifsc,
    upi_id = excluded.upi_id,
    review_status = 'UNDER_REVIEW', reviewed_at = null,
    reviewed_by = null, review_reason = null, updated_at = now();

  insert into public.tbl_partner_application_history(
    user_id, from_status, to_status, actor_user_id, snapshot
  ) values (me, previous_status, next_status, me, to_jsonb(profile));

  perform private.enqueue_notification(
    me, 'partner_application_submitted', 'Partner application submitted',
    case when next_status='APPROVED'
      then 'Your Partner profile was updated. Payout details are under review; paid hosting remains available.'
      else 'Your application is under review. We will notify you when a decision is made.' end,
    me::text, null, jsonb_build_object('status',next_status,'payout_status','UNDER_REVIEW')
  );
  return private.get_my_partner_profile();
end $$;

