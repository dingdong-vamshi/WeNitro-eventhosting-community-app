create or replace function private.enforce_partner_paid_hosting()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if coalesce(new.is_paid,false) or coalesce(new.price,0)>0 then
    if not private.has_active_partner(new.created_by) then
      raise exception 'Only an approved Partner can host paid activities' using errcode='42501';
    end if;
    if coalesce(new.price,0)<=0 then raise exception 'Paid activities require a positive price'; end if;
    new.is_paid := true;
    new.payment_collection_mode := coalesce(nullif(new.payment_collection_mode,''),'cashfree');
  else
    new.is_paid := false;
    new.price := 0;
  end if;
  return new;
end $$;

