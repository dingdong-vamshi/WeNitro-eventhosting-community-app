function find(node, predicate) { if (predicate(node)) return node; return ts.forEachChild(node, n => find(n, predicate)); }
const removal = find(appAst, n => ts.isVariableDeclaration(n) && n.name.getText(appAst) === 'deleteOwnMessage');
